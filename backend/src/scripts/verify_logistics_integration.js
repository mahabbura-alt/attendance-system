async function serve(f){
  // The API under review uses production routes/services and an isolated database.
  const express=require('express');
  const dbPath=require.resolve('../config/db');require.cache[dbPath]={id:dbPath,filename:dbPath,loaded:true,exports:{pool:f.pool}};
  process.env.JWT_SECRET=randomUUID()+randomUUID();
  const jwt=require('jsonwebtoken');
  const planner=jwt.sign({id:f.scope.user_id},process.env.JWT_SECRET),reviewer=jwt.sign({id:f.review.user_id},process.env.JWT_SECRET);
  const app=express();app.use(express.json());
  app.get('/__fixture/session',(req,res)=>res.json({planner,reviewer}));
  app.use('/api/logistics',require('../routes/logistics.routes'));
  app.use(express.static(path.join(__dirname,'../../../admin-dashboard')));
  app.use((err,req,res,next)=>{console.error(err.message);res.status(500).json({error:err.message});});
  app.listen(8768,'127.0.0.1',async()=>{
    assert.equal((await fetch('http://127.0.0.1:8768/api/logistics/dashboard')).status,401);
    assert.equal((await fetch('http://127.0.0.1:8768/api/logistics/dashboard?project=foreign',{headers:{Authorization:`Bearer ${planner}`}})).status,403);
    assert.equal((await fetch('http://127.0.0.1:8768/api/logistics/dashboard',{headers:{Authorization:`Bearer ${planner}`}})).status,200);
    console.log('PASS: real JWT middleware 401, unauthorized project 403, authenticated dashboard 200.');
    console.log('ISOLATED LOGISTICS PREVIEW http://127.0.0.1:8768/test-fixtures/logistics-preview.html');
  });
}
